n = int(input())

summa_brick = 0

# 2. Внешний цикл: перебираем уровни от 1 до n включительно
for level in range(1, n + 1):

    # Внутренний цикл: перебираем каждый кирпич на текущем уровне.
    # Так как range(level) выдает level элементов, цикл выполнится ровно столько раз,
    # сколько кирпичей на этом уровне.
    for brick in range(level):
        # К общей сумме прибавляем число, написанное на кирпиче (номер уровня)
        summa_brick += level

# 3. Выводим итоговый результат
print(summa_brick)